const DICTS = { it, en };

// Every UI language, in the order the Settings dropdown lists them. Each name is
// written in its own language so it can be found whatever the UI currently is.
// To add one: a dictionary above, an entry here, a locale in LOCALES.
export const LANGUAGES = [
  { code: 'it', name: 'Italiano' },
  { code: 'en', name: 'English' },
];
const isLang = (code) => Object.prototype.hasOwnProperty.call(DICTS, code);

let lang = 'en';
const listeners = new Set();

function detect() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (isLang(stored)) return stored;
  } catch {
    /* storage disabled */
  }
  // The first browser language we have a dictionary for; English otherwise.
  for (const tag of navigator.languages || [navigator.language || '']) {
    const code = String(tag).slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return 'en';
}

export function initI18n() {
  lang = detect();
  document.documentElement.setAttribute('lang', lang);
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (!isLang(next) || next === lang) return;
  lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* session-only */
  }
  document.documentElement.setAttribute('lang', next);
  for (const fn of listeners) fn(next);
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function interpolate(s, vars) {
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : s;
}

// Look up a key (falling back to the other language, then to the key itself so
// a missing string is visible rather than blank). With a numeric `n` the plural
// forms `<key>_one` / `<key>_other` are used.
export function t(key, vars) {
  const dict = DICTS[lang];
  let s = dict[key];
  if (s == null && vars && typeof vars.n === 'number') {
    const form = `${key}_${vars.n === 1 ? 'one' : 'other'}`;
    s = dict[form] != null ? dict[form] : DICTS.en[form];
  }
  if (s == null) s = DICTS.en[key];
  if (s == null) return key;
  return interpolate(s, vars ? { ...vars, n: vars.n != null ? fmtNumber(vars.n) : vars.n } : vars);
}

// --- numbers, dates -------------------------------------------------------------
// The BCP 47 tag for Intl / toLocale*String calls. In English it returns the tag
// the call site already used (`'en-US'`, or undefined for the browser default),
// so English output is exactly what it was before Italian existed.
export function locale(enTag) {
  return lang === 'it' ? LOCALES.it : enTag;
}

// No grouping: a count reads "1000" in both languages, as it always has.
export function fmtNumber(n) {
  if (n == null || !Number.isFinite(Number(n))) return '';
  return new Intl.NumberFormat(LOCALES[lang] || LOCALES.en, { maximumFractionDigits: 2, useGrouping: false }).format(Number(n));
}
